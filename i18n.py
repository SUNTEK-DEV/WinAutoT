def lang() -> str:
    return _current


def set_lang(language: str) -> None:
    global _current
    if language not in STRINGS:
        raise ValueError(f"unsupported language: {language}")
    _current = language


def toggle_lang() -> str:
    set_lang(EN if _current == ZH else ZH)
    return _current


def t(key: str, **kwargs) -> str:
    table = STRINGS.get(_current) or STRINGS[ZH]
    text = table.get(key) or STRINGS[ZH].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text


def item_name(item_id: str) -> str:
    return t(f"item.{item_id}")


def status_label(status: str) -> str:
    return t(f"status.{status}")


def method_label(method: str) -> str:
    return t(f"method.{method}")
